"""Rebuild the result tables of ``docs/baselines.md`` from ``results/results.json``.

    pixi run -e dev python scripts/build_baselines_doc.py

Everything between ``<!-- results:begin -->`` and ``<!-- results:end -->`` is generated; the
rest of the document is hand-written. Tables: our arms and official checkpoints evaluated in
our harness (success, 95 % CI, seeds), then published numbers of other VLAs (reference only).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- results:begin -->", "<!-- results:end -->"
SUITES = ["libero_spatial", "libero_object", "libero_goal", "libero_10"]


def pct(x) -> str:
    return "–" if x is None else f"{100 * x:.1f}"


def render(entries: list[dict]) -> str:
    out = ["*Generated by `scripts/build_baselines_doc.py` from `results/results.json`; do not edit by hand.*", ""]
    ours = [e for e in entries if e["source"] in ("ours", "official_checkpoint")]
    if ours:
        out += ["| Arm | Source | Suite | Training data / steps | Seeds | Success % | 95 % CI | Notes |",
                "|---|---|---|---|---|---|---|---|"]
        for e in sorted(ours, key=lambda e: (e["suite"], e["source"], e["arm"])):
            tr = e.get("training") or {}
            ci = "–" if not e.get("ci95") else f"{pct(e['ci95'][0])}–{pct(e['ci95'][1])}"
            seeds = ", ".join(str(s) for s in tr.get("seeds", [])) or ", ".join(str(s) for s in (e.get("eval") or {}).get("eval_seeds", []))
            out.append(f"| {e['arm']} | {e['source']} | {e['suite']} | {tr.get('data') or '–'} / {tr.get('steps') or '–'} | "
                       f"{seeds or '–'} | {pct(e['success'])} | {ci} | {e['notes']} |")
    else:
        out.append("No arm of ours has been evaluated yet.")
    pub = [e for e in entries if e["source"] == "published"]
    if pub:
        out += ["", "Published numbers (reference only; other data, models and harnesses):", "",
                "| Model | " + " | ".join(SUITES) + " | Citation | Date | Caveats |", "|---" * (len(SUITES) + 4) + "|"]
        for m in dict.fromkeys(e["arm"] for e in pub):
            row = {e["suite"]: e for e in pub if e["arm"] == m}
            first = next(iter(row.values()))
            out.append(f"| {m} | " + " | ".join(pct(row[s]["success"]) if s in row else "–" for s in SUITES)
                       + f" | {first['citation']} | {first['date']} | {first['notes']} |")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default="results/results.json")
    ap.add_argument("--doc", default="docs/baselines.md")
    args = ap.parse_args()
    entries = json.loads((ROOT / args.results).read_text())
    doc = (ROOT / args.doc).read_text()
    if BEGIN not in doc or END not in doc:
        raise SystemExit(f"{args.doc} has no {BEGIN} ... {END} block")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: f"{BEGIN}\n{render(entries)}\n{END}", doc, flags=re.S)
    (ROOT / args.doc).write_text(new)
    print(f"updated {args.doc}")


if __name__ == "__main__":
    main()
